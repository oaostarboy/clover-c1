def redeem(event, key, current=lambda: True):
    return origin.redeem_human_ingress(
        event, platform='telegram', profile=current_profile(), session_id='root',
        session_key=key, run_generation=1, is_current=current,
    )


@pytest.mark.asyncio
async def test_actual_adapter_mint_moves_once_and_writes_one_exact_row(replay, tmp_path):
    from telegram import Update
    from tests.test_telegram_queue_native_application import native_app
    x = replay
    # Telegram only mints genuine origin in its admitted TEXT handler, not in
    # _build_message_event or the media handler. Exercise that real producer.
    update_data = photo(x.bot, 91).to_dict()
    update_data['message'].pop('photo')
    update_data['message'].pop('media_group_id')
    update_data['message']['text'] = '/queue pricing'
    update = Update.de_json(update_data, x.bot)
    captured = []
    enqueue = x.adapter._enqueue_text_event
    def capture(event):
        captured.append(event)
        enqueue(event)
    x.adapter._enqueue_text_event = capture
    x.adapter._text_batch_delay_seconds = .01
    async with native_app(x) as app:
        await app.process_update(update)
        await asyncio.wait_for(asyncio.gather(*x.adapter._pending_text_batch_tasks.values()), 2)
    event = captured[0]
    queued = waiting(x)[0]
    assert queued is not event
    proof = redeem(queued, x.key)
    assert proof is not None
    assert redeem(event, x.key) is None
    assert redeem(queued, x.key) is None
    assert redeem(dataclasses.replace(queued), x.key) is None
    db = SessionDB(db_path=tmp_path / 'origin.db')
    try:
        db.create_session('root', source='telegram')
        first = {'role': 'user', 'content': queued.text, 'human_ingress': proof}
        second = dict(first)
        db.append_messages_batch('root', [first, second])
        receipt = db.get_human_origin('root', first['_row_id'])
        assert receipt is not None and receipt.ingress_event_id == proof.event_id
        assert db.get_human_origin('root', second['_row_id']) is None
        assert db.consume_human_origin('root', first['_row_id'], consumer='test')
        assert db.get_human_origin('root', first['_row_id']) is None
    finally:
        origin.retire_human_ingress(proof)
        db.close()


@pytest.mark.asyncio
async def test_bound_queue_origin_keeps_original_digest_scope_and_stop(replay, tmp_path):
    from agent.workstreams import Scope
    x = replay
    event = x.adapter._build_message_event(photo(x.bot, 92, '/queue pricing').message, MessageType.TEXT)
    event.text = '/queue pricing'
    # Discard the adapter's legacy unbound issue, then mint a scoped input owner.
    origin.retire_human_ingress(redeem(event, x.key))
    scope = Scope(profile=current_profile(), project='project', audience='private', root='root')
    live = {'ok': True}
    assert origin.mint_human_ingress(event, platform='telegram', scope=scope,
                                     original_text=event.text, is_current=lambda: live['ok'])
    await x.adapter.handle_message(event)
    queued = waiting(x)[0]
    proof = redeem(queued, x.key)
    assert proof is not None
    assert proof.scope == origin.scope_binding(scope)
    assert origin.ingress_matches_content(proof, event.text)
    # Moving identity does not attest that rewritten/generated bytes were typed.
    assert not origin.ingress_matches_content(proof, queued.text)
    db = SessionDB(db_path=tmp_path / 'bound.db')
    try:
        db.create_session('root', source='telegram')
        row = {'role': 'user', 'content': queued.text, 'human_ingress': proof}
        db.append_messages_batch('root', [row])
        assert db.get_human_origin('root', row['_row_id']) is None
    finally:
        db.close()
    assert origin.ingress_is_valid(proof, profile=current_profile())
    live['ok'] = False
    assert not origin.ingress_is_valid(proof, profile=current_profile())
    origin.retire_human_ingress(proof)
    assert redeem(event, x.key) is None


